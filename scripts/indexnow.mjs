// ============================================================
// credit-simulator — IndexNow submission
//
// Announces the sitemap's URLs to IndexNow, which fans out to Bing and
// Yandex. Google does not participate, so this does nothing for Google.
//
//   node scripts/indexnow.mjs --dry-run   # print the payload, send nothing
//   node scripts/indexnow.mjs --wait      # wait for the deploy, then submit
//   node scripts/indexnow.mjs             # submit now
//
// The key file in web/public/ is the single source of truth. IndexNow's own
// ownership contract is that the file is named after the key and contains it,
// so this script derives the key from the file instead of reading it from a
// secret or an env var — there is nothing to keep in sync, and no way for the
// committed key and the submitted key to drift apart. The key is public by
// design: it is served at the site root.
//
// Unlike a static-sitemap project, this sitemap is generated by
// web/app/sitemap.ts, so there is no committed copy to read. The live sitemap
// is the only source of URLs, which also shapes --wait below.
// ============================================================

import { readdirSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PUBLIC_DIR = join(ROOT, 'web', 'public');
const ENDPOINT = 'https://api.indexnow.org/indexnow';

/** IndexNow keys: 8–128 chars of a-z, A-Z, 0-9 and dashes. */
const KEY_FILE = /^([A-Za-z0-9-]{8,128})\.txt$/;

/** Deploy wait: 20 attempts, 15 s apart — five minutes. */
const POLL_ATTEMPTS = 20;
const POLL_INTERVAL_MS = 15_000;

function findKey() {
  const matches = readdirSync(PUBLIC_DIR).flatMap((name) => {
    const key = name.match(KEY_FILE)?.[1];
    if (!key) return [];
    // The contract: the file repeats its own name. This also rules out any
    // other text file that happens to live in web/public/.
    const contents = readFileSync(join(PUBLIC_DIR, name), 'utf-8').trim();
    return contents === key ? [key] : [];
  });

  if (matches.length !== 1) {
    throw new Error(
      `expected exactly one IndexNow key file in web/public/ (named <key>.txt and containing <key>), found ${matches.length}`
    );
  }
  return matches[0];
}

/**
 * The site's host. The sitemap is generated from NEXT_PUBLIC_SITE_URL at build
 * time, so this script needs the same value to know where to read it. In CI it
 * comes from the SITE_URL repository variable; see docs/indexnow.md.
 */
function findHost() {
  const flag = process.argv.find((arg) => arg.startsWith('--host='))?.slice('--host='.length);
  const raw = flag ?? process.env.SITE_URL ?? process.env.NEXT_PUBLIC_SITE_URL;
  if (!raw) {
    throw new Error('no site URL: pass --host=https://example.com or set SITE_URL');
  }
  const { protocol, host } = new URL(raw);
  if (protocol !== 'https:') {
    // IndexNow rejects a non-https host, and a localhost URL means the
    // repository variable was never set.
    throw new Error(`site URL must be https, got ${raw}`);
  }
  return host;
}

function sitemapUrls(xml) {
  // Trimmed: a reformatted sitemap can wrap a <loc>, and the whitespace would
  // then break the submitted URL.
  return [...xml.matchAll(/<loc>([^<]+)<\/loc>/g)].map((match) => match[1].trim());
}

async function liveSitemap(host) {
  const response = await fetch(`https://${host}/sitemap.xml`, { cache: 'no-store' });
  if (!response.ok) throw new Error(`sitemap answered ${response.status}`);

  const urls = sitemapUrls(await response.text());
  if (urls.length === 0) throw new Error('the live sitemap lists no <loc>');

  const foreign = urls.filter((url) => new URL(url).host !== host);
  if (foreign.length > 0) {
    // IndexNow answers 422 when a URL does not belong to the declared host.
    // Here it also means NEXT_PUBLIC_SITE_URL on Vercel disagrees with SITE_URL
    // in CI, which is worth failing on rather than guessing.
    throw new Error(`sitemap host is not ${host}: ${foreign.join(', ')}`);
  }
  return urls;
}

/**
 * A push and its deploy race each other, so submitting straight away can
 * announce URLs that are still serving the previous build, or a key file that
 * is not deployed yet — which IndexNow answers with a bare 403 for every URL.
 *
 * There is no committed sitemap to compare the live one against, so freshness
 * cannot be checked the way a static-sitemap project checks it. Readiness is
 * checked by consequence instead, which is what actually matters: the key file
 * is live and correct, the sitemap is served, and every URL it lists answers
 * 200. A page added in this commit is therefore still covered — its URL 404s
 * until its deploy is live.
 */
async function waitForDeploy(host, key) {
  /** Resolves to null when ready, or to the reason it is not. */
  async function keyFileReady() {
    const response = await fetch(`https://${host}/${key}.txt`, { cache: 'no-store' });
    if (!response.ok) return `key file answered ${response.status}`;
    return (await response.text()).trim() === key ? null : 'key file contents do not match';
  }

  async function urlsReady() {
    const urls = await liveSitemap(host);
    const statuses = await Promise.all(
      urls.map(async (url) => {
        const response = await fetch(url, { method: 'HEAD', cache: 'no-store' });
        return response.ok ? null : `${url} answered ${response.status}`;
      })
    );
    const broken = statuses.filter(Boolean);
    return broken.length === 0 ? null : broken.join('; ');
  }

  for (let attempt = 1; attempt <= POLL_ATTEMPTS; attempt += 1) {
    try {
      const reasons = (await Promise.all([keyFileReady(), urlsReady()])).filter(Boolean);
      if (reasons.length === 0) {
        console.log(`key file and every sitemap URL are live (attempt ${attempt})`);
        return;
      }
      console.log(`attempt ${attempt}: ${reasons.join('; ')}`);
    } catch (error) {
      console.log(`attempt ${attempt}: ${error.message}`);
    }

    if (attempt < POLL_ATTEMPTS) {
      await new Promise((resolve) => setTimeout(resolve, POLL_INTERVAL_MS));
    }
  }

  throw new Error('the deployment never became fully reachable — refusing to submit');
}

async function submit(payload) {
  const response = await fetch(ENDPOINT, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json; charset=utf-8' },
    body: JSON.stringify(payload),
  });

  const body = await response.text();
  // 200 accepted, 202 accepted with key validation pending (normal on first use).
  if (response.status !== 200 && response.status !== 202) {
    throw new Error(`IndexNow answered ${response.status}: ${body || '(empty body)'}`);
  }
  console.log(`IndexNow accepted ${payload.urlList.length} URLs (HTTP ${response.status})`);
}

const dryRun = process.argv.includes('--dry-run');
const wait = process.argv.includes('--wait');

const key = findKey();
const host = findHost();

console.log(`host: ${host}`);
console.log(`key file: web/public/${key}.txt`);

if (wait && !dryRun) await waitForDeploy(host, key);

// Read after waiting, so the submitted list is the one that was just verified.
const urls = await liveSitemap(host);
console.log(`urls (${urls.length}):`);
for (const url of urls) console.log(`  ${url}`);

if (dryRun) {
  console.log('--dry-run: nothing submitted');
} else {
  await submit({ host, key, urlList: urls });
}
